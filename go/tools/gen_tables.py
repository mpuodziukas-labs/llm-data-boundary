#!/usr/bin/env python3
"""Generate go/pdp/tables_gen.go from the Python interpreter's own Unicode data.

The Python policy point uses unicodedata (NFKC, category Cf), str.isspace, str.isalnum and
\\d (decimal digits). Go's standard library has none of the NFKC data and its Unicode version
differs, so the Go port reads tables produced here and stays equal to the reference by
construction. Run: python3 go/tools/gen_tables.py
"""
import os
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "pdp", "tables_gen.go")
MAX = 0x110000
HANGUL_S, HANGUL_E = 0xAC00, 0xD7A3


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if pred(chr(cp)):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def fmt_ranges(name, rs):
    lines = ["var %s = []rng{" % name]
    row = []
    for lo, hi in rs:
        row.append("{0x%X, 0x%X}," % (lo, hi))
        if len(row) == 6:
            lines.append("\t" + " ".join(row))
            row = []
    if row:
        lines.append("\t" + " ".join(row))
    lines.append("}")
    return "\n".join(lines)


def main():
    cf = ranges(lambda c: unicodedata.category(c) == "Cf")
    space = ranges(lambda c: c.isspace())
    alnum = ranges(lambda c: c.isalnum())

    # decimal digits: every Nd run is ten consecutive code points with values 0..9
    decimals = {cp for cp in range(MAX) if chr(cp).isdecimal()}
    zeros = [cp for cp in sorted(decimals) if unicodedata.decimal(chr(cp)) == 0]
    covered = set()
    for z in zeros:
        for k in range(10):
            assert (z + k) in decimals and unicodedata.decimal(chr(z + k)) == k, hex(z)
            covered.add(z + k)
    assert covered == decimals, "an Nd code point lies outside a run of ten"

    ccc = []
    cp = 0
    while cp < MAX:
        v = unicodedata.combining(chr(cp))
        if v:
            s = cp
            while cp + 1 < MAX and unicodedata.combining(chr(cp + 1)) == v:
                cp += 1
            ccc.append((s, cp, v))
        cp += 1

    nfkd = []
    for cp in range(MAX):
        if HANGUL_S <= cp <= HANGUL_E:
            continue
        c = chr(cp)
        d = unicodedata.normalize("NFKD", c)
        if d != c:
            nfkd.append((cp, [ord(x) for x in d]))

    pairs = []
    for cp in range(MAX):
        dec = unicodedata.decomposition(chr(cp))
        if not dec or dec.startswith("<"):
            continue
        parts = dec.split()
        if len(parts) != 2:
            continue
        a, b = int(parts[0], 16), int(parts[1], 16)
        if unicodedata.normalize("NFC", chr(a) + chr(b)) == chr(cp):
            pairs.append((a, b, cp))
    pairs.sort()

    flat, idx = [], []
    for cp, seq in nfkd:
        idx.append((cp, len(flat), len(seq)))
        flat.extend(seq)

    o = []
    o.append("// Code generated by go/tools/gen_tables.py; DO NOT EDIT.")
    o.append("// Source: Python %s, unicodedata %s." % (sys.version.split()[0], unicodedata.unidata_version))
    o.append("")
    o.append("package pdp")
    o.append("")
    o.append('const unicodeVersion = "%s"' % unicodedata.unidata_version)
    o.append("")
    o.append("// cfRanges: general category Cf (dropped by normalize).")
    o.append(fmt_ranges("cfRanges", cf))
    o.append("")
    o.append("// spaceRanges: str.isspace, which is what Python's \\s and str.strip use.")
    o.append(fmt_ranges("spaceRanges", space))
    o.append("")
    o.append("// alnumRanges: str.isalnum, which with '_' defines Python's \\w and so \\b.")
    o.append(fmt_ranges("alnumRanges", alnum))
    o.append("")
    o.append("// decimalZeros: code point of the digit zero of every Nd run of ten (Python's \\d).")
    o.append("var decimalZeros = []rune{")
    row = []
    for z in zeros:
        row.append("0x%X," % z)
        if len(row) == 8:
            o.append("\t" + " ".join(row))
            row = []
    if row:
        o.append("\t" + " ".join(row))
    o.append("}")
    o.append("")
    o.append("// cccRanges: canonical combining class of every code point with a non-zero class.")
    o.append("var cccRanges = []cccRange{")
    row = []
    for lo, hi, v in ccc:
        row.append("{0x%X, 0x%X, %d}," % (lo, hi, v))
        if len(row) == 5:
            o.append("\t" + " ".join(row))
            row = []
    if row:
        o.append("\t" + " ".join(row))
    o.append("}")
    o.append("")
    o.append("// nfkdIndex: code point -> slice of nfkdData holding its full NFKD (Hangul syllables are algorithmic).")
    o.append("var nfkdIndex = []nfkdEntry{")
    row = []
    for cp, off, n in idx:
        row.append("{0x%X, %d, %d}," % (cp, off, n))
        if len(row) == 5:
            o.append("\t" + " ".join(row))
            row = []
    if row:
        o.append("\t" + " ".join(row))
    o.append("}")
    o.append("")
    o.append("var nfkdData = []rune{")
    row = []
    for r in flat:
        row.append("0x%X," % r)
        if len(row) == 10:
            o.append("\t" + " ".join(row))
            row = []
    if row:
        o.append("\t" + " ".join(row))
    o.append("}")
    o.append("")
    o.append("// compPairs: primary composites (first, second, composite), sorted by (first, second).")
    o.append("var compPairs = []compPair{")
    row = []
    for a, b, c in pairs:
        row.append("{0x%X, 0x%X, 0x%X}," % (a, b, c))
        if len(row) == 4:
            o.append("\t" + " ".join(row))
            row = []
    if row:
        o.append("\t" + " ".join(row))
    o.append("}")
    o.append("")
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(o))
    print("wrote %s: cf=%d space=%d alnum=%d zeros=%d ccc=%d nfkd=%d pairs=%d"
          % (os.path.normpath(OUT), len(cf), len(space), len(alnum), len(zeros), len(ccc), len(nfkd), len(pairs)))


if __name__ == "__main__":
    main()
